/** 演示模式的选课通道；订阅（xk:watch*）在桌面端仍走 xkwatch.ts（它经 call 查到的也是演示数据） */
export const demoXk: Omit<XkHandlers, 'xk:watches' | 'xk:watch' | 'xk:unwatch'> = {
  'xk:context': async () => {
    const total = [...new Set(chosen.map((s) => s.courseCode))].reduce((n, code) => n + credit(code), 9)
    return { xn: '2026-2027', xq: '1', maxChoices: MAX, credits: { total, regular: total, short: 0 }, categories: CATEGORIES }
  },
  'xk:courses': async (key) => {
    const id = key.split('|')[0]
    return id === 'xk_b' ? courses : courses.filter((c) => c.tab === id)
  },
  'xk:search': async (keyword, onlyAvailable) =>
    courses
      .filter((c) => c.name.includes(keyword) && (!onlyAvailable || sections.get(c.code)!.some((s) => s.remaining)))
      .map((c) => ({ ...c, tab: 'xk_9', keyword })),
  'xk:sections': async (c) => sections.get(c.code) ?? [],
  'xk:selected': async () => chosen.map((s) => ({ ...s })),
  'xk:select': async (s) => {
    if (chosen.some((x) => x.id === s.id)) return { status: 'already', message: '已在志愿中' }
    const group = groupOf(s)
    const members = chosen.filter((x) => x.group === group)
    if (members.length >= MAX) return { status: 'rejected', message: '志愿数已满' }
    put(s, 'pending', members.length + 1)
    return { status: 'saved', message: '已加入志愿' }
  },
  'xk:drop': async (id) => {
    const i = chosen.findIndex((x) => x.id === id)
    if (i < 0) return { status: 'already', message: '已不在志愿中' }
    const [removed] = chosen.splice(i, 1)
    chosen
      .filter((x) => x.group === removed.group)
      .sort((a, b) => (a.order ?? 0) - (b.order ?? 0))
      .forEach((x, n) => (x.order = n + 1))
    return { status: 'saved', message: '已退选' }
  },
  'xk:reorder': async (ids) => {
    ids.forEach((id, n) => {
      const s = chosen.find((x) => x.id === id)
      if (s) s.order = n + 1
    })
    return { status: 'saved', message: '已调整顺序' }
  },
  'cls:teacher': async (name) => {
    const r = RATINGS[name]
    if (!r) return null
    const teacher: ClsTeacher = {
      id: Object.keys(RATINGS).indexOf(name) + 1,
      name,
      college: r[3],
      rating: r[0],
      ratingCount: r[1],
      rollCall: r[2],
      courses: r[4].map(([n, gpa, sample]) => ({ name: n, gpa, sample })),
      commentCount: 6,
      url: 'https://chalaoshi.de/'
    }
    return teacher
  },
  // 每位教师取六条，按 id 错开；最新按日期排
  'cls:comments': async (id, sort) => {
    const list: ClsComment[] = Array.from({ length: 6 }, (_, k) => {
      const n = (id * 5 + k * 7) % COMMENTS.length
      const [text, likes, date] = COMMENTS[n]
      return { id: id * 100 + n, text, likes, date }
    })
    return sort === 'time' ? list.sort((a, b) => b.date.localeCompare(a.date)) : list.sort((a, b) => b.likes - a.likes)
  }
}
